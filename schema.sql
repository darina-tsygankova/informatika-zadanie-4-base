CREATE TABLE "Ученики" (
    "ID_ученика" INTEGER NOT NULL PRIMARY KEY,
    "Фамилия" VARCHAR(40) NOT NULL,
    "Имя" VARCHAR(40) NOT NULL,
    "Класс" VARCHAR(4) NOT NULL,
    "Дата_рождения" DATE NOT NULL
);

CREATE TABLE "Успеваемость" (
    "ID_Оценки" INTEGER NOT NULL PRIMARY KEY,
    "ID_ученика" INTEGER NOT NULL,
    "Четверть" INTEGER NOT NULL,
    "Оценка" INTEGER NOT NULL,
    CONSTRAINT "FK_Успеваемость_Ученики"
        FOREIGN KEY ("ID_ученика")
        REFERENCES "Ученики" ("ID_ученика")
);

