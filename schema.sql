-- 1. Сортировка таблицы "Ученики" по классу, затем по фамилии.
SELECT *
FROM "Ученики"
ORDER BY "Класс" ASC, "Фамилия" ASC;

-- 2. Фильтр: только ученики 9-х классов.
SELECT *
FROM "Ученики"
WHERE "Класс" LIKE '9%';

-- 3. Фильтр: успеваемость только за 1-ю и 2-ю четверти.
SELECT *
FROM "Успеваемость"
WHERE "Четверть" IN (1, 2)
ORDER BY "Четверть" ASC, "ID_Оценки" ASC;

-- 4. Девятиклассники, имеющие за 1 четверть оценку 5.
SELECT
    "Ученики"."Фамилия",
    "Ученики"."Имя",
    "Ученики"."Класс",
    "Успеваемость"."Четверть",
    "Успеваемость"."Оценка"
FROM "Ученики"
INNER JOIN "Успеваемость"
    ON "Ученики"."ID_ученика" = "Успеваемость"."ID_ученика"
WHERE
    "Ученики"."Класс" LIKE '9%'
    AND "Успеваемость"."Четверть" = 1
    AND "Успеваемость"."Оценка" = 5
ORDER BY "Ученики"."Фамилия" ASC;
